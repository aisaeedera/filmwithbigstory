/**
 * Arabic-first digital-invitation demo library — data-driven renderer source.
 *
 * Source of truth: the approved 64-record seed matrix
 *   `03_Shared_Assets/wedding_invitation_demos/WEDDING_INVITATION_DEMO_SEED_64.json`
 * (8 occasion categories × 8 original style families; 32 static, 16 carousel,
 * 16 animated). This module transforms that matrix into typed records the
 * gallery + demo-detail renderers consume. One renderer, 64 records — never 64
 * copied components (site architecture §6).
 *
 * Hard rules carried into this data:
 *  - Every record is a DEMO. `demoLabelAr` always contains نموذج and is shown on
 *    every card. Nothing here is presented as a completed paid client project.
 *  - Visuals are original CSS/SVG/vector compositions generated by
 *    `InvitationPoster` from the style family + palette below. No stock photos,
 *    no competitor artwork, no relabelled work.
 *  - Demo names (راشد ومريم …) are original placeholder names, not real clients.
 *  - Demo-detail pages are `noindex,follow` at launch (`indexable: false`). SEO
 *    value comes from the service pages and the filterable gallery, not 64
 *    doorway pages (architecture §3).
 *
 * The Arabic color descriptors from the seed (`palette_ar`) are kept verbatim as
 * human-readable captions; the machine `palette` hex arrays are original to Big
 * Story and drive the SVG renderer.
 */

