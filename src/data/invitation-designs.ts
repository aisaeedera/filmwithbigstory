export const invitationDemoSlugs = invitationDemos.map((d) => d.slug);

const demoBySlug = new Map(invitationDemos.map((d) => [d.slug, d]));
const demoById = new Map(invitationDemos.map((d) => [d.id, d]));

export function getDemo(slug: string): InvitationDemo | undefined {
  return demoBySlug.get(slug);
}

export function getDemoById(id: string): InvitationDemo | undefined {
  return demoById.get(id);
}

export function demosForCategory(categorySlug: CategorySlug): InvitationDemo[] {
  return invitationDemos.filter((d) => d.categorySlug === categorySlug);
}

/** Demos for the service page that owns a given service slug (or [] if none). */
export function demosForService(serviceSlug: string): InvitationDemo[] {
  const cat = invitationCategories.find((c) => c.serviceSlug === serviceSlug);
  return cat ? demosForCategory(cat.slug) : [];
}

export function getCategory(slug: CategorySlug): InvitationCategory | undefined {
  return categoryBySlug[slug];
}

/** Localised category label. */
export function categoryLabel(cat: InvitationCategory, locale: Locale): string {
  return locale === "ar" ? cat.nameAr : cat.nameEn;
}
